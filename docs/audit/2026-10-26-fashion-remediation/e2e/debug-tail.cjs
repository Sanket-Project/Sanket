const { chromium } = require('C:/Users/admin/Desktop/Prisma/frontend/node_modules/playwright');
const fs = require('node:fs');
const fixture = JSON.parse(fs.readFileSync(__dirname+'/fixture.json','utf8'));
(async()=>{
 const browser = await chromium.launch();
 const page = await browser.newPage({baseURL:'http://127.0.0.1:5174',viewport:{width:1280,height:720}});
 page.setDefaultTimeout(15000);
 await page.goto('/login');
 await page.locator('#signin-workspace').fill(fixture.slug);
 await page.locator('#signin-email').fill(fixture.email);
 await page.locator('#signin-password').fill(fixture.password);
 await page.locator('form[aria-label="Sign in form"] button[type="submit"]').click();
 await page.waitForURL('**/workspace');
 const coveragePromise=page.waitForResponse(r=>r.url().includes('/inventory/coverage')&&r.status()===200);
 await page.goto('/workspace/inventory');
 const coverage=await(await coveragePromise).json();
 console.log('coverage',coverage.skus.find(s=>s.sku_code==='KURTI-M').locations);
 await page.getByPlaceholder('Filter by SKU code or location…').fill('KURTI-M');
 await page.screenshot({path:__dirname+'/debug-inventory.png'});
 await page.goto('/workspace/decisions');
 const refreshed=page.waitForResponse(r=>r.url().includes('/decisions/refresh')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Recompute from latest forecast'}).click();
 console.log('refresh',await(await refreshed).json());
 await page.getByRole('button',{name:'Show working'}).first().click();
 await page.getByRole('button',{name:'Accept',exact:true}).first().waitFor();
 console.log('accept available');
 const presetsPromise=page.waitForResponse(r=>r.url().includes('/scenarios/presets'));
 await page.goto('/workspace/scenarios');
 const presets=await(await presetsPromise).json();
 const simulation=page.waitForResponse(r=>r.url().includes('/scenarios/simulate')&&r.request().method()==='POST'&&r.request().postDataJSON()?.preset===presets.presets[0].key);
 await page.getByRole('button',{name:presets.presets[0].label,exact:true}).click();
 const response=await simulation;
 console.log('scenario',response.status(),presets.presets[0].key);
 await page.getByRole('heading',{name:presets.presets[0].label,exact:true}).waitFor();
 await page.screenshot({path:__dirname+'/debug-scenario.png'});
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
